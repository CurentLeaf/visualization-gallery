library(ggplot2)
library(ggdist)
d <- read.csv('draws.csv')
base <- ggplot(d, aes(x=value,y=report)) + theme_minimal(base_size=11) + labs(x='Temperature (C)',y='Report',subtitle='Invented normal, skewed, and bimodal distributions; not calibrated source confidence')
p <- base + stat_halfeye(.width=c(.5,.95),fill='#60a5fa') + ggtitle('Shape, spread, and overlapping simulated estimates')
ggsave('site/uncertainty.png',p,width=11,height=11,dpi=140)
p <- base + stat_dotsinterval(quantiles=20,.width=c(.5,.95),fill='#60a5fa') + ggtitle('20 equal-probability dots per synthetic report')
ggsave('site/uncertainty-dots.png',p,width=11,height=12,dpi=140)
p <- base + stat_pointinterval(.width=c(.5,.95),point_interval=median_qi) + ggtitle('Medians and central 50% / 95% intervals')
ggsave('site/uncertainty-intervals.png',p,width=11,height=10,dpi=140)
