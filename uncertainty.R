library(ggplot2)
library(ggdist)
d <- read.csv('draws.csv')
base <- ggplot(d, aes(x=value,y=report)) + theme_minimal(base_size=12) + labs(x='Temperature (C)',y='Report')
p <- base + stat_halfeye(.width=c(.5,.95),fill='#60a5fa') + ggtitle('Synthetic temperature distributions')
ggsave('site/uncertainty.png',p,width=10,height=6,dpi=140)
p <- base + stat_dotsinterval(quantiles=20,.width=c(.5,.95),fill='#60a5fa') + ggtitle('Equal-probability quantile dots: 20 dots per report')
ggsave('site/uncertainty-dots.png',p,width=10,height=7,dpi=140)
p <- base + stat_pointinterval(.width=c(.5,.95),point_interval=median_qi) + ggtitle('Medians with central 50% and 95% intervals')
ggsave('site/uncertainty-intervals.png',p,width=10,height=6,dpi=140)
